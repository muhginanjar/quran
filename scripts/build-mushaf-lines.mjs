#!/usr/bin/env node
// Build data/mushaf-lines.js — layout baris per halaman (Madinah 15 baris, 604 hal).
// Sumber: zonetecde/mushaf-layout (ISC) — JSON per halaman mushaf QPC2.
// Jalankan: node scripts/build-mushaf-lines.mjs
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CACHE = resolve(ROOT, 'scripts/.cache/zonetec');
const BASE = 'https://raw.githubusercontent.com/zonetecde/mushaf-layout/v2/mushaf/QPC2';

async function getPage(n) {
  const file = resolve(CACHE, `page-${String(n).padStart(3, '0')}.json`);
  try { return JSON.parse(await readFile(file, 'utf8')); } catch { /* unduh */ }
  const res = await fetch(`${BASE}/page-${String(n).padStart(3, '0')}.json`);
  if (!res.ok) throw new Error(`hal ${n}: HTTP ${res.status}`);
  const buf = await res.text();
  await mkdir(CACHE, { recursive: true });
  await writeFile(file, buf);
  return JSON.parse(buf);
}

const pages = [];
for (let n = 1; n <= 604; n++) {
  const d = await getPage(n);
  if (d.page !== n) throw new Error(`nomor halaman tidak cocok: ${d.page} vs ${n}`);
  const out = [];
  for (let i = 0; i < d.lines.length; i++) {
    const ln = d.lines[i];
    const next = d.lines[i + 1];
    const centered = i === d.lines.length - 1 || (next && (next.type === 'surah-header' || next.type === 'basmala'));
    if (ln.type === 'surah-header') out.push([1, +ln.surah, 1]);
    else if (ln.type === 'basmala') out.push([2]);
    else out.push(centered ? [0, ln.text, 1] : [0, ln.text]);
  }
  if (out.length > 15) throw new Error(`hal ${n}: ${out.length} baris`);
  pages.push(out);
}

const payload = { b: new Date().toISOString().slice(0, 10), src: 'zonetecde/mushaf-layout (ISC)', p: pages };
const out = resolve(ROOT, 'data/mushaf-lines.js');
await writeFile(out, `/* Quran Offline — layout baris mushaf Madinah (604 hal × maks 15 baris). Generated by scripts/build-mushaf-lines.mjs — JANGAN edit manual. */\nwindow.MUSHAF604=${JSON.stringify(payload)};\n`);
console.log(`✓ data/mushaf-lines.js ${(await readFile(out)).length.toLocaleString('id-ID')} byte — 604 halaman, ${pages.reduce((a, x) => a + x.length, 0)} baris, build ${payload.b}`);
