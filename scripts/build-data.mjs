#!/usr/bin/env node
// Build data/quran-data.js dari sumber publik (sekali jalan, hasilnya bundled offline).
// Sumber: fawazahmed0/quran-api (teks + terjemahan), api.quran.com (metadata surah).
// Jalankan: node scripts/build-data.mjs
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CACHE = resolve(ROOT, 'scripts/.cache');
const CDN = 'https://cdn.jsdelivr.net/gh/fawazahmed0/quran-api@1/editions';
const SRC = {
  ar: [`${CDN}/ara-quranuthmanihaf.json`, 'Quran Uthmani Hafs'],
  k: [`${CDN}/ind-indonesianislam.json`, 'Kemenag RI'],
  s: [`${CDN}/ind-thesabiqcompany.json`, 'Tafsir Assaibiq'],
  meta: ['https://api.quran.com/api/v4/chapters?language=id', 'quran.com chapters (id)'],
};

async function getJSON(url, key) {
  const file = resolve(CACHE, `${key}.json`);
  try { return JSON.parse(await readFile(file, 'utf8')); } catch { /* fetch di bawah */ }
  console.log(`↓ ${key} …`);
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${key}: HTTP ${res.status}`);
  const buf = await res.text();
  await mkdir(CACHE, { recursive: true });
  await writeFile(file, buf);
  return JSON.parse(buf);
}

const dAr = await getJSON(SRC.ar[0], 'ar');
const dK = await getJSON(SRC.k[0], 'k');
const dS = await getJSON(SRC.s[0], 's');
const dM = await getJSON(SRC.meta[0], 'meta');

// cek konsistensi
const N = 6236;
for (const [name, d] of [['ar', dAr], ['k', dK], ['s', dS]]) {
  const v = d.quran;
  if (!Array.isArray(v) || v.length !== N) throw new Error(`${name}: ${v?.length} ayat, bukan ${N}`);
}
const chapters = dM.chapters;
if (chapters.length !== 114) throw new Error('chapters != 114');
if (chapters.reduce((a, c) => a + c.verses_count, 0) !== N) throw new Error('total verses_count != 6236');

// indeks per (chapter,verse)
const idx = new Map();
for (let i = 0; i < N; i++) idx.set(`${dAr.quran[i].chapter}:${dAr.quran[i].verse}`, i);

const surahs = [];
const verses = []; // [ar, kemenag, assaibiq] per ayat, urut global 1..6236
let g = 0;
for (const c of chapters) {
  const first = g;
  for (let v = 1; v <= c.verses_count; v++) {
    const i = idx.get(`${c.id}:${v}`);
    if (i == null) throw new Error(`ayat hilang ${c.id}:${v}`);
    const tA = dAr.quran[i].text, tK = dK.quran[i].text, tS = dS.quran[i].text;
    if (!tA || !tK || !tS) throw new Error(`teks kosong ${c.id}:${v}`);
    verses.push([tA, tK, tS]);
    g++;
  }
  surahs.push({
    n: c.id, a: c.name_arabic, l: c.name_simple, m: c.translated_name.name,
    r: c.revelation_place === 'makkah' ? 0 : 1,
    c: c.verses_count, f: first + 1, p: c.pages[0],
  });
}
if (g !== N) throw new Error(' ayat terjembatani: ' + g);

const payload = {
  b: new Date().toISOString().slice(0, 10),
  src: { ar: SRC.ar[1], k: SRC.k[1], s: SRC.s[1] },
  s: surahs,
  v: verses,
};

const out = resolve(ROOT, 'data/quran-data.js');
await mkdir(dirname(out), { recursive: true });
await writeFile(out, `/* Quran Offline — data terpadu. Generated by scripts/build-data.mjs — JANGAN edit manual. */\nwindow.QURAN=${JSON.stringify(payload)};\n`);
const size = (await readFile(out)).length;
console.log(`✓ data/quran-data.js ${(size / 1048576).toFixed(2)} MB — ${surahs.length} surah, ${verses.length} ayat, build ${payload.b}`);
